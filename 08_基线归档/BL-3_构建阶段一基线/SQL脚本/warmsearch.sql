-- =====================================================================
-- WarmSearch 校园失物招领平台 二次开发 数据库脚本
-- 基于开源项目 https://github.com/lijinghailjh/WarmSearch
-- 新增模块：信用认领机制、保卫处贵重物品处理流程
-- 数据库：MySQL 5.7+  字符集：utf8mb4
-- 说明：本脚本可一次性执行；若库已存在会先重建。
-- =====================================================================

DROP DATABASE IF EXISTS warmsearch;
CREATE DATABASE warmsearch DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE warmsearch;

-- =====================================================================
-- 一、基础模块（对应 WarmSearch 已有功能，字段依据 WarmSearch-Web 页面还原）
-- =====================================================================

-- 1. 学生用户表 ------------------------------------------------------
DROP TABLE IF EXISTS suser;
CREATE TABLE suser (
  id           BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  username     VARCHAR(50)  NOT NULL COMMENT '学号/登录账号',
  password     VARCHAR(100) NOT NULL COMMENT '密码(MD5)',
  name         VARCHAR(50)  DEFAULT NULL COMMENT '姓名',
  phone_num    VARCHAR(20)  DEFAULT NULL COMMENT '手机号',
  profession   VARCHAR(100) DEFAULT NULL COMMENT '专业',
  article      VARCHAR(255) DEFAULT NULL COMMENT '个性签名',
  email        VARCHAR(100) DEFAULT NULL COMMENT '邮箱',
  avatar       VARCHAR(255) DEFAULT NULL COMMENT '头像/证件照URL',
  status       TINYINT      NOT NULL DEFAULT 1 COMMENT '账号状态：1正常 0封禁',
  create_time  DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time  DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_suser_username (username)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '学生用户表';

-- 2. 后台用户表（管理员 + 保卫处工作人员）-----------------------------
DROP TABLE IF EXISTS teacher;
CREATE TABLE teacher (
  id           BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  username     VARCHAR(50)  NOT NULL COMMENT '登录账号',
  password     VARCHAR(100) NOT NULL COMMENT '密码(MD5)',
  name         VARCHAR(50)  DEFAULT NULL COMMENT '姓名',
  position     VARCHAR(50)  DEFAULT NULL COMMENT '职位',
  phone_num    VARCHAR(20)  DEFAULT NULL COMMENT '电话号码',
  role         VARCHAR(20)  NOT NULL DEFAULT 'ADMIN' COMMENT '角色：ADMIN平台管理员 SECURITY保卫处',
  status       TINYINT      NOT NULL DEFAULT 1 COMMENT '状态：1正常 0停用',
  create_time  DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time  DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_teacher_username (username)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '后台用户表(管理员/保卫处)';

-- 3. 物品分类表 ------------------------------------------------------
DROP TABLE IF EXISTS category;
CREATE TABLE category (
  id           BIGINT      NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  ctitle       VARCHAR(50) NOT NULL COMMENT '类别名称',
  sort         INT         NOT NULL DEFAULT 0 COMMENT '排序(升序)',
  create_time  DATETIME    DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '物品分类表';

-- 4. 招领物品表（拾到物品，寻失主，对应 /goodsfirst）------------------
DROP TABLE IF EXISTS goods;
CREATE TABLE goods (
  id             BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  img_url        VARCHAR(255) DEFAULT NULL COMMENT '物品图片URL',
  img_name       VARCHAR(100) DEFAULT NULL COMMENT '物品名称',
  img_desc       VARCHAR(500) DEFAULT NULL COMMENT '物品描述',
  gid            BIGINT       DEFAULT NULL COMMENT '物品分类ID',
  status         VARCHAR(20)  NOT NULL DEFAULT 'WAITING' COMMENT '状态：WAITING待认领 CLAIMING认领中 CLAIMED已认领 OFFLINE已下架',
  contact_name   VARCHAR(50)  DEFAULT NULL COMMENT '联系人',
  contact        VARCHAR(30)  DEFAULT NULL COMMENT '联系方式',
  found_location VARCHAR(200) DEFAULT NULL COMMENT '拾获地点',
  found_time     DATETIME     DEFAULT NULL COMMENT '拾获时间',
  is_valuable    TINYINT      NOT NULL DEFAULT 0 COMMENT '是否贵重物品：0否 1是',
  view_count     INT          NOT NULL DEFAULT 0 COMMENT '点击量',
  publisher_id   BIGINT       DEFAULT NULL COMMENT '发布者(拾获者)学生ID',
  create_time    DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time    DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  KEY idx_goods_gid (gid),
  KEY idx_goods_status (status),
  KEY idx_goods_publisher (publisher_id),
  KEY idx_goods_valuable (is_valuable)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '招领物品表(拾到物品寻失主)';

-- 5. 寻物启事表（丢失物品，寻物，对应 /findlist）----------------------
DROP TABLE IF EXISTS findinfo;
CREATE TABLE findinfo (
  id             BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  fl_img_url     VARCHAR(255) DEFAULT NULL COMMENT '物品图片URL',
  fl_img_desc    VARCHAR(500) DEFAULT NULL COMMENT '物品描述',
  fl_name        VARCHAR(50)  DEFAULT NULL COMMENT '联系人',
  fl_contact     VARCHAR(30)  DEFAULT NULL COMMENT '联系方式',
  fl_status      VARCHAR(20)  NOT NULL DEFAULT 'OPEN' COMMENT '状态：OPEN寻找中 FOUND已找到 CLOSED已关闭',
  gid            BIGINT       DEFAULT NULL COMMENT '物品分类ID',
  lost_location  VARCHAR(200) DEFAULT NULL COMMENT '丢失地点',
  lost_time      DATETIME     DEFAULT NULL COMMENT '丢失时间',
  publisher_id   BIGINT       DEFAULT NULL COMMENT '发布者学生ID',
  create_time    DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time    DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  KEY idx_find_publisher (publisher_id),
  KEY idx_find_status (fl_status)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '寻物启事表(丢失物品寻物)';

-- 6. 物品详情图表（对应 /goodsdetail）---------------------------------
DROP TABLE IF EXISTS goods_detail;
CREATE TABLE goods_detail (
  id           BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  goods_id     BIGINT       NOT NULL COMMENT '所属招领物品ID',
  dimg_url     VARCHAR(255) NOT NULL COMMENT '详情图URL',
  sort         INT          NOT NULL DEFAULT 0 COMMENT '排序',
  create_time  DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (id),
  KEY idx_detail_goods (goods_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '物品详情图表';

-- 7. 轮播图表（小程序 /unbo 与 PC /pccarousel 合一，用 type 区分）-----
DROP TABLE IF EXISTS carousel;
CREATE TABLE carousel (
  id           BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  img_url      VARCHAR(255) NOT NULL COMMENT '图片URL',
  type         VARCHAR(10)  NOT NULL DEFAULT 'MINI' COMMENT '归属：MINI小程序 PC电脑端',
  link         VARCHAR(255) DEFAULT NULL COMMENT '跳转链接',
  sort         INT          NOT NULL DEFAULT 0 COMMENT '排序',
  status       TINYINT      NOT NULL DEFAULT 1 COMMENT '状态：1显示 0隐藏',
  create_time  DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (id),
  KEY idx_carousel_type (type)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '轮播图表';

-- 8. 普通认领记录表（对应 /attestation，普通物品认领台账）-------------
DROP TABLE IF EXISTS attestation;
CREATE TABLE attestation (
  id           BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  goods_id     BIGINT       DEFAULT NULL COMMENT '招领物品ID',
  goods_name   VARCHAR(100) DEFAULT NULL COMMENT '被认领物品名称',
  user_id      BIGINT       DEFAULT NULL COMMENT '认领人学生ID',
  user_name    VARCHAR(50)  DEFAULT NULL COMMENT '认领人姓名',
  contact      VARCHAR(30)  DEFAULT NULL COMMENT '认领人联系方式',
  number       VARCHAR(50)  DEFAULT NULL COMMENT '学号或工号',
  address      VARCHAR(200) DEFAULT NULL COMMENT '地址',
  img_url      VARCHAR(255) DEFAULT NULL COMMENT '认领人证件照',
  claim_time   DATETIME     DEFAULT NULL COMMENT '认领时间',
  create_time  DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (id),
  KEY idx_att_goods (goods_id),
  KEY idx_att_user (user_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '普通认领记录表';

-- =====================================================================
-- 二、信用认领模块（新增）
-- =====================================================================

-- 9. 用户信用分表 ----------------------------------------------------
DROP TABLE IF EXISTS credit_score;
CREATE TABLE credit_score (
  id                 BIGINT      NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  user_id            BIGINT      NOT NULL COMMENT '学生用户ID',
  score              INT         NOT NULL DEFAULT 100 COMMENT '当前信用分(初始100)',
  level              VARCHAR(20) NOT NULL DEFAULT 'GOOD' COMMENT '信用等级：EXCELLENT优秀 GOOD良好 NORMAL一般 POOR较差',
  return_count       INT         NOT NULL DEFAULT 0 COMMENT '成功归还/被归还次数',
  false_claim_count  INT         NOT NULL DEFAULT 0 COMMENT '虚假认领次数',
  create_time        DATETIME    DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time        DATETIME    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_credit_user (user_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '用户信用分表';

-- 10. 信用变动流水表 --------------------------------------------------
DROP TABLE IF EXISTS credit_log;
CREATE TABLE credit_log (
  id           BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  user_id      BIGINT       NOT NULL COMMENT '学生用户ID',
  change_value INT          NOT NULL COMMENT '变动分值(正数加分/负数扣分)',
  type         VARCHAR(20)  NOT NULL COMMENT '类型：RETURN归还加分 FALSE_CLAIM虚假认领扣分 PUNISH恶意行为扣分 MANUAL人工调整',
  reason       VARCHAR(255) DEFAULT NULL COMMENT '变动原因',
  biz_id       BIGINT       DEFAULT NULL COMMENT '关联业务ID(认领申请/物品)',
  operator_id  BIGINT       DEFAULT NULL COMMENT '操作人(后台用户)ID',
  create_time  DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (id),
  KEY idx_log_user (user_id),
  KEY idx_log_type (type)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '信用变动流水表';

-- 11. 认领申请表（支撑认领优先级与审核流程）---------------------------
DROP TABLE IF EXISTS claim_application;
CREATE TABLE claim_application (
  id                BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  goods_id          BIGINT       NOT NULL COMMENT '招领物品ID',
  applicant_id      BIGINT       NOT NULL COMMENT '申请人(学生)ID',
  applicant_name    VARCHAR(50)  DEFAULT NULL COMMENT '申请人姓名',
  contact           VARCHAR(30)  DEFAULT NULL COMMENT '联系方式',
  credential_type   VARCHAR(20)  DEFAULT NULL COMMENT '凭证类型：IDCARD身份证 PURCHASE购买凭证 OTHER其他',
  credential_img    VARCHAR(255) DEFAULT NULL COMMENT '认领凭证图片URL',
  description       VARCHAR(500) DEFAULT NULL COMMENT '认领说明/物品独有特征',
  priority          INT          NOT NULL DEFAULT 0 COMMENT '认领优先级(取申请时信用分)',
  status            VARCHAR(20)  NOT NULL DEFAULT 'PENDING' COMMENT '状态：PENDING待审核 PASSED审核通过 REJECTED驳回 CONFIRMED已确认认领 FALSE虚假认领 CANCELED已取消',
  audit_teacher_id  BIGINT       DEFAULT NULL COMMENT '审核人(后台用户)ID',
  audit_remark      VARCHAR(255) DEFAULT NULL COMMENT '审核备注',
  apply_time        DATETIME     DEFAULT NULL COMMENT '申请时间',
  audit_time        DATETIME     DEFAULT NULL COMMENT '审核时间',
  confirm_time      DATETIME     DEFAULT NULL COMMENT '确认认领时间',
  create_time       DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time       DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  KEY idx_claim_goods (goods_id),
  KEY idx_claim_applicant (applicant_id),
  KEY idx_claim_status (status)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '认领申请表';

-- =====================================================================
-- 三、保卫处贵重物品处理模块（新增）
-- =====================================================================

-- 12. 贵重物品表 ------------------------------------------------------
DROP TABLE IF EXISTS valuables_item;
CREATE TABLE valuables_item (
  id               BIGINT         NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  goods_id         BIGINT         NOT NULL COMMENT '关联招领物品ID',
  item_name        VARCHAR(100)   DEFAULT NULL COMMENT '物品名称',
  item_category    VARCHAR(50)    DEFAULT NULL COMMENT '物品类别',
  estimated_value  DECIMAL(10, 2) DEFAULT NULL COMMENT '预估价值(元)',
  img_url          VARCHAR(255)   DEFAULT NULL COMMENT '物品图片',
  description      VARCHAR(500)   DEFAULT NULL COMMENT '物品描述',
  report_user_id   BIGINT         DEFAULT NULL COMMENT '上报人ID',
  report_source    VARCHAR(10)    NOT NULL DEFAULT 'MANUAL' COMMENT '上报方式：AUTO自动识别 MANUAL人工标记',
  status           VARCHAR(20)    NOT NULL DEFAULT 'PENDING_AUDIT' COMMENT '状态：PENDING_AUDIT待审核 IN_CUSTODY保管中 IN_VERIFICATION核验中 CLAIMED已认领 REJECTED审核驳回 UNCLAIMED无人认领',
  custody_location VARCHAR(200)   DEFAULT NULL COMMENT '保管位置',
  security_id      BIGINT         DEFAULT NULL COMMENT '负责保卫处人员ID',
  report_time      DATETIME       DEFAULT NULL COMMENT '上报时间',
  create_time      DATETIME        DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time      DATETIME        DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_val_goods (goods_id),
  KEY idx_val_status (status),
  KEY idx_val_security (security_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '贵重物品表(保卫处)';

-- 13. 贵重物品流转记录表（处理台账 + 认领凭证）------------------------
DROP TABLE IF EXISTS valuables_flow;
CREATE TABLE valuables_flow (
  id                 BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  valuables_id       BIGINT       NOT NULL COMMENT '贵重物品ID',
  goods_id           BIGINT       DEFAULT NULL COMMENT '招领物品ID',
  action             VARCHAR(20)  NOT NULL COMMENT '动作：REPORT上报 AUDIT_PASS审核通过 CUSTODY入库保管 CLAIM_APPLY认领申请 VERIFY_OFFLINE线下核验 CLAIM_COMPLETE认领完成 REJECT驳回 TRANSFER移交',
  from_status        VARCHAR(20)  DEFAULT NULL COMMENT '变更前状态',
  to_status          VARCHAR(20)  DEFAULT NULL COMMENT '变更后状态',
  claimer_name       VARCHAR(50)  DEFAULT NULL COMMENT '认领人姓名',
  claimer_contact    VARCHAR(30)  DEFAULT NULL COMMENT '认领人联系方式',
  claimer_number     VARCHAR(50)  DEFAULT NULL COMMENT '认领人学号/身份证号',
  purchase_proof_img VARCHAR(255) DEFAULT NULL COMMENT '购买凭证图片',
  id_proof_img       VARCHAR(255) DEFAULT NULL COMMENT '身份证明图片',
  verify_remark      VARCHAR(255) DEFAULT NULL COMMENT '核验备注',
  operator_id        BIGINT       DEFAULT NULL COMMENT '操作保卫处人员ID',
  operator_name      VARCHAR(50)  DEFAULT NULL COMMENT '操作人姓名',
  operate_time       DATETIME     DEFAULT NULL COMMENT '操作时间',
  create_time        DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (id),
  KEY idx_flow_valuables (valuables_id),
  KEY idx_flow_goods (goods_id),
  KEY idx_flow_action (action)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '贵重物品流转记录表(处理台账)';

